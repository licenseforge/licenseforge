import { chromium } from "@playwright/test";
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
const errs = []; p.on("pageerror", (e) => errs.push(e.message));
await p.goto("http://localhost:8080/");
await p.getByRole("link", { name: "Continue to sign in" }).click();
await p.locator("#username").fill("demo"); await p.locator("#password").fill("demo"); await p.locator("#kc-login").click();
await p.waitForURL((u) => u.port === "8080");
await p.waitForTimeout(1000);
console.log("landed:", p.url());
await p.getByRole("button", { name: "New tenant" }).click();
await p.getByLabel(/^Slug/).fill("acme");
await p.getByLabel("Name", { exact: true }).fill("Acme Software");
await p.getByLabel("Owner's email").fill("demo@licenseforge.local");
await p.getByRole("button", { name: "Create and invite" }).click();
await p.waitForTimeout(800);
const link = await p.getByRole("dialog").locator("input, textarea, code").first().evaluate((e) => e.value || e.textContent);
console.log("invite shown:", /invite#token=/.test(link));
await p.goto(link.startsWith("http") ? link : "http://localhost:8080" + link.trim());
await p.getByRole("button", { name: "Accept invitation" }).click();
await p.waitForURL(/\/t\/acme/); await p.waitForTimeout(800);
console.log("in tenant:", p.url(), "errors:", errs);
await p.screenshot({ path: process.argv[2] });
await b.close();
